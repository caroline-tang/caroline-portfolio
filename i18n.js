const LANG_KEY = "portfolio-lang";

function getLang() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === "en" || saved === "zh") return saved;
  // Default for first visit: English (visitors can switch to 中)
  return "en";
}

function setLang(lang) {
  if (lang !== "zh" && lang !== "en") return;
  localStorage.setItem(LANG_KEY, lang);
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  const root = document.documentElement;
  if (root.dataset.titleZh && root.dataset.titleEn) {
    document.title = lang === "zh" ? root.dataset.titleZh : root.dataset.titleEn;
  }
  applyI18n(lang);
  document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
    btn.setAttribute("aria-pressed", btn.dataset.langTarget === lang ? "true" : "false");
  });
}

function applyI18n(lang) {
  const dict = I18N[lang];
  if (!dict) return;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key && dict[key] !== undefined) {
      el.textContent = dict[key];
    }
  });
  document.querySelectorAll("[data-i18n-href]").forEach((el) => {
    const key = el.getAttribute("data-i18n-href");
    if (key && dict[key] !== undefined) {
      el.setAttribute("href", dict[key]);
    }
  });
}

function initI18n() {
  setLang(getLang());
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
    btn.addEventListener("click", () => {
      const target = btn.dataset.langTarget;
      if (target === "zh" || target === "en") setLang(target);
    });
  });
});
